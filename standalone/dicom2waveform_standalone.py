def _field_comments() -> dict[str, tuple[str, dict[str, list[str]]]]:
    """{class name: (docstring, {field: comment lines directly above the field})}, read from the
    source of this module (also works when it is part of the single-file standalone script)."""
    import ast
    import inspect
    import sys

    src = inspect.getsource(sys.modules[__name__])
    lines = src.splitlines()
    out = {}
    for node in ast.parse(src).body:
        if not (isinstance(node, ast.ClassDef) and node.name.endswith("Config")):
            continue
        fields = {}
        for st in node.body:
            if isinstance(st, ast.AnnAssign) and isinstance(st.target, ast.Name):
                block, i = [], st.lineno - 2
                while i >= 0 and lines[i].lstrip().startswith("#"):
                    block.insert(0, lines[i].lstrip()[1:].rstrip())
                    i -= 1
                fields[st.target.id] = [b[1:] if b.startswith(" ") else b for b in block]
        out[node.name] = (ast.get_docstring(node) or "", fields)
    return out


def _yaml_value(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        plain = v and v.replace("_", "").isalnum() and v.lower() not in ("null", "true", "false", "yes", "no")
        return v if plain else '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_yaml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {_yaml_value(x)}" for k, x in v.items()) + "}"
    raise TypeError(f"cannot write {type(v).__name__} to YAML")


def config_yaml(cfg: PipelineConfig | None = None, header: str = YAML_HEADER) -> str:
    """The configuration as YAML, with the documentation comments of this module."""
    cfg = cfg or PipelineConfig()
    docs = _field_comments()
    rule = "# " + "-" * 93
    out = [f"# {line}".rstrip() for line in header.splitlines()]

    def comments(cls_name: str, name: str, indent: str) -> list[str]:
        return [f"{indent}# {c}".rstrip() for c in docs.get(cls_name, ("", {}))[1].get(name, [])]

    for f in dataclasses.fields(cfg):
        val = getattr(cfg, f.name)
        if dataclasses.is_dataclass(val):
            title = docs.get(type(val).__name__, (f.name, {}))[0].splitlines()[0]
            out += ["", rule, f"# {title}", rule, f"{f.name}:"]
            for g in dataclasses.fields(val):
                out += comments(type(val).__name__, g.name, "  ")
                out.append(f"  {g.name}: {_yaml_value(getattr(val, g.name))}")
        else:
            out += [""] + comments(type(cfg).__name__, f.name, "")
            out.append(f"{f.name}: {_yaml_value(val)}")
    return "\n".join(out) + "\n"


def write_config(cfg: PipelineConfig | None, path: str | Path, header: str = YAML_HEADER) -> None:
    """Write a configuration as commented YAML, loadable by load_config."""
    Path(path).write_text(config_yaml(cfg, header), encoding="utf8")


# ==================================================================================================
# io.py: DICOM reading and ultrasound region calibration.
# ==================================================================================================
# The spectral display is located and calibrated from the DICOM Ultrasound
# Region Calibration module (SequenceOfUltrasoundRegions) rather than from the
# pixels: the header states the region box, the time and velocity increment per
# pixel and the zero-velocity row exactly.
#
# Region coordinates in DICOM are 0-based and inclusive, which matches NumPy
# indexing directly (MATLAB needed +1).

UNIT_CM = 3
UNIT_SECONDS = 4
UNIT_CM_PER_S = 7

# RegionDataType codes (DICOM PS3.3 C.8.5.5.1.2)
DATA_TYPE_NAMES = {
    1: "tissue",
    2: "color_flow",
    3: "pw_spectral",
    4: "cw_spectral",
    5: "doppler_mean_trace",
    6: "doppler_mode_trace",
    7: "doppler_max_trace",
    8: "volume_trace",
    10: "ecg_trace",
    11: "pulse_trace",
    12: "phonocardiogram_trace",
}


@dataclass
class Region:
    """One item of SequenceOfUltrasoundRegions."""

    x0: int
    y0: int
    x1: int  # inclusive
    y1: int  # inclusive
    dx: float  # physical units per pixel in x
    dy: float  # physical units per pixel in y (downwards)
    units_x: int
    units_y: int
    data_type: int
    spatial_format: int
    ref_x0: int | None = None
    ref_y0: int | None = None

    @property
    def width(self) -> int:
        return self.x1 - self.x0 + 1

    @property
    def height(self) -> int:
        return self.y1 - self.y0 + 1

    @property
    def is_spectral(self) -> bool:
        return self.units_x == UNIT_SECONDS and self.units_y == UNIT_CM_PER_S

    @property
    def is_bmode(self) -> bool:
        return self.units_x == UNIT_CM and self.units_y == UNIT_CM

    @property
    def data_type_name(self) -> str:
        return DATA_TYPE_NAMES.get(self.data_type, f"type_{self.data_type}")


@dataclass
class DicomImage:
    path: str
    pixels: np.ndarray  # (H, W) uint8 or (H, W, 3) uint8, RGB
    photometric: str
    regions: list[Region]
    meta: dict[str, Any] = field(default_factory=dict)

    @property
    def is_rgb(self) -> bool:
        return self.pixels.ndim == 3


def _get(ds: Any, name: str, default: Any = None) -> Any:
    try:
        val = getattr(ds, name)
    except AttributeError:
        return default
    return default if val is None or val == "" else val


def _parse_regions(ds: Any) -> list[Region]:
    regions = []
    for r in _get(ds, "SequenceOfUltrasoundRegions", []) or []:
        regions.append(
            Region(
                x0=int(r.RegionLocationMinX0),
                y0=int(r.RegionLocationMinY0),
                x1=int(r.RegionLocationMaxX1),
                y1=int(r.RegionLocationMaxY1),
                dx=float(_get(r, "PhysicalDeltaX", np.nan)),
                dy=float(_get(r, "PhysicalDeltaY", np.nan)),
                units_x=int(_get(r, "PhysicalUnitsXDirection", 0)),
                units_y=int(_get(r, "PhysicalUnitsYDirection", 0)),
                data_type=int(_get(r, "RegionDataType", 0)),
                spatial_format=int(_get(r, "RegionSpatialFormat", 0)),
                ref_x0=None if _get(r, "ReferencePixelX0") is None else int(r.ReferencePixelX0),
                ref_y0=None if _get(r, "ReferencePixelY0") is None else int(r.ReferencePixelY0),
            )
        )
    return regions


def _to_uint8_rgb_or_grey(ds: Any, arr: np.ndarray) -> tuple[np.ndarray, str]:
    photometric = str(_get(ds, "PhotometricInterpretation", "MONOCHROME2"))
    if photometric.startswith("YBR"):
        from pydicom.pixels import convert_color_space

        arr = convert_color_space(arr, photometric, "RGB")
        photometric = "RGB"
    elif photometric == "PALETTE COLOR":
        from pydicom.pixels import apply_color_lut

        arr = apply_color_lut(arr, ds)
        if arr.dtype != np.uint8:
            arr = (arr / 257).astype(np.uint8)
        photometric = "RGB"
    elif photometric == "MONOCHROME1":
        arr = arr.max() - arr
        photometric = "MONOCHROME2"
    if arr.dtype != np.uint8:
        bits = int(_get(ds, "BitsStored", 8))
        arr = np.clip(arr.astype(np.float64) / (2**bits - 1) * 255, 0, 255).astype(np.uint8)
    # RGB images whose three channels are identical are still handled as RGB,
    # so that overlay colour logic is uniform; nothing is lost.
    return arr, photometric


META_TAGS = [
    "Manufacturer", "ManufacturerModelName", "SoftwareVersions", "Modality",
    "Rows", "Columns", "PhotometricInterpretation", "BitsAllocated", "BitsStored",
    "NumberOfFrames", "FrameTime", "CineRate", "RescaleSlope", "RescaleIntercept",
    "WindowCenter", "WindowWidth", "PixelSpacing", "HeartRate",
    "TransducerData", "ProcessingFunction", "SeriesDescription", "StudyDescription",
    "SOPInstanceUID",
]


def load_dicom(path: str | Path, frame: int = 0) -> DicomImage:
    """Read a DICOM and return its pixel array, regions and metadata.

    Only non-identifying technical metadata is recorded in `meta`.
    """
    ds = pydicom.dcmread(str(path))
    arr = ds.pixel_array
    n_frames = int(_get(ds, "NumberOfFrames", 1) or 1)
    photometric = str(_get(ds, "PhotometricInterpretation", ""))
    if n_frames > 1:
        arr = arr[frame]
    elif arr.ndim == 3 and photometric == "MONOCHROME2" and arr.shape[-1] != 3:
        arr = arr[frame]
    arr, photometric = _to_uint8_rgb_or_grey(ds, arr)

    meta: dict[str, Any] = {}
    for tag in META_TAGS:
        val = _get(ds, tag)
        if val is not None:
            meta[tag] = val if isinstance(val, (int, float, str)) else str(val)
    meta["TransferSyntax"] = str(ds.file_meta.TransferSyntaxUID.name) if hasattr(ds, "file_meta") else ""
    meta["HasWaveformSequence"] = "WaveformSequence" in ds
    return DicomImage(path=str(path), pixels=arr, photometric=photometric,
                      regions=_parse_regions(ds), meta=meta)


class RegionError(ValueError):
    pass


def spectral_region(img: DicomImage) -> Region:
    """The spectral Doppler region: seconds horizontally, cm/s vertically.

    Selected by physical unit codes, never by item order (the order varies).
    """
    cands = [r for r in img.regions if r.is_spectral]
    if not cands:
        raise RegionError("No spectral Doppler region (s vs cm/s) in SequenceOfUltrasoundRegions")
    if len(cands) > 1:
        # Prefer the largest one (e.g. a duplicated/trace region)
        cands.sort(key=lambda r: r.width * r.height, reverse=True)
    r = cands[0]
    if not np.isfinite(r.dy) or r.dy == 0:
        raise RegionError(f"PhysicalDeltaY must be finite and non-zero, got {r.dy}")
    if not np.isfinite(r.dx) or r.dx <= 0:
        raise RegionError(f"PhysicalDeltaX must be finite and positive, got {r.dx}")
    return r


def bmode_region_above(img: DicomImage, spec: Region) -> Region | None:
    """The B-mode region directly above the spectral region (ECG runs along its lower edge)."""
    cands = [r for r in img.regions if r.is_bmode and r.y1 <= spec.y0]
    if not cands:
        return None
    return max(cands, key=lambda r: r.y1)


# ==================================================================================================
# render.py: From the rendered spectral display to a calibrated scalar intensity image.
# ==================================================================================================
# The DICOM holds a *rendering* of the Doppler spectrogram, not the spectrum:
# grey levels (or a colour map for TDI) after log compression, with overlays
# drawn on top. This module
#
# 1. crops the spectral region given by the header,
# 2. finds the overlays (drawn baseline, time markers, ECG trace, text) and
#    marks them as missing rather than as signal or background,
# 3. converts colour to a scalar display level (0..255),
# 4. finds the sweep (write position of the circular display buffer), which
#    holds no data,
# 5. attaches the calibration: velocity per row, time per column.
#
# Intensities are display levels. They are monotonic in Doppler power, but only
# a proxy for it: see `level_to_power`.

# Luminance of the brightest colour of the Philips copper TDI map is ~150;
# scale luminance so that colour-map images use roughly the same 0..255 range
# as greyscale images (noise margins are in grey levels).
COLORMAP_LEVEL_SCALE = 255.0 / 160.0

LUMA = np.array([0.299, 0.587, 0.114])


@dataclass
class Spectrogram:
    """Calibrated spectral Doppler image.

    Row r has velocity (r - zero_row) * dy (cm/s); column c has time c * dt (s)
    before any sweep alignment. All arrays are in raw display column order;
    `order` gives the permutation to oldest -> newest.
    """

    level: np.ndarray  # (H, W) float32 display level 0..255 (overlays filled)
    valid: np.ndarray  # (H, W) bool: False on overlays and in the sweep
    zero_row: float
    dy: float  # cm/s per row downwards (negative: velocity increases upwards)
    dt: float  # s per column
    sweep: np.ndarray  # (W,) bool: column holds no data
    order: np.ndarray  # (W,) int: column order oldest -> newest
    colormap: str  # 'grey' or 'colour'
    modality: str  # 'PW', 'CW' or 'TDI'
    region: Region
    baseline_rows: np.ndarray  # rows covered by the drawn baseline
    rgb: np.ndarray | None = None  # cropped display for plotting (H, W, 3)
    overlay: np.ndarray | None = None  # (H, W) bool overlay mask
    info: dict[str, Any] = field(default_factory=dict)
    clicks: np.ndarray | None = None  # (W,) bool: valve-click columns
    click_strength: np.ndarray | None = None  # (W,) transient height (robust SDs)
    click_mode: str = "bridge"

    @property
    def shape(self) -> tuple[int, int]:
        return self.level.shape

    @property
    def velocity(self) -> np.ndarray:
        return (np.arange(self.level.shape[0]) - self.zero_row) * self.dy

    @property
    def v_limits(self) -> tuple[float, float]:
        v = self.velocity
        return float(v.min()), float(v.max())

    @property
    def display_height(self) -> int:
        """Rows of the displayed spectral region (unchanged by aliasing unwrapping)."""
        return int(self.region.height)

    @property
    def display_v_limits(self) -> tuple[float, float]:
        """Velocity limits of the display as rendered by the scanner (the Nyquist
        window for PW), also after aliasing unwrapping."""
        z0 = self.info.get("display_zero_row", self.zero_row)
        v = (np.array([0, self.display_height - 1]) - z0) * self.dy
        return float(v.min()), float(v.max())

    def row_of_velocity(self, v: np.ndarray | float) -> np.ndarray | float:
        return np.asarray(v) / self.dy + self.zero_row


def _colour_match(rgb: np.ndarray, colour: np.ndarray, tol: int) -> np.ndarray:
    return np.all(np.abs(rgb.astype(np.int16) - np.asarray(colour, np.int16)) <= tol, axis=-1)


def _dominant_colour(pixels: np.ndarray) -> tuple[np.ndarray | None, int]:
    """Most common non-black colour among (N, 3) pixels, and its count."""
    px = pixels.reshape(-1, 3)
    px = px[px.sum(1) > 0]
    if len(px) == 0:
        return None, 0
    u, c = np.unique(px, axis=0, return_counts=True)
    i = int(np.argmax(c))
    return u[i].astype(int), int(c[i])


def _runs(mask: np.ndarray) -> list[tuple[int, int]]:
    """Inclusive (start, end) of runs of True in a 1-D mask."""
    m = np.concatenate([[False], mask.astype(bool), [False]])
    d = np.diff(m.astype(np.int8))
    starts = np.flatnonzero(d == 1)
    ends = np.flatnonzero(d == -1) - 1
    return list(zip(starts.tolist(), ends.tolist()))


def find_baseline(rgb: np.ndarray, zero_row: float, cfg: RenderConfig) -> tuple[np.ndarray, np.ndarray | None, np.ndarray]:
    """Drawn zero-velocity line near the header's zero row.

    Returns (rows covered by the line, line colour, per-column presence).
    The line is the most common non-black colour on the rows around
    zero_row; rows where that colour covers more than half the columns belong
    to the line.
    """
    H, W, _ = rgb.shape
    z = int(round(zero_row))
    lo, hi = max(0, z - cfg.baseline_search_rows), min(H - 1, z + cfg.baseline_search_rows)
    best, best_count = None, 0
    for r in range(lo, hi + 1):
        col, cnt = _dominant_colour(rgb[r])
        if col is not None and cnt > best_count:
            best, best_count = col, cnt
    if best is None or best_count < 0.3 * W:
        return np.array([], int), None, np.ones(W, bool)
    rows = [r for r in range(lo, hi + 1)
            if _colour_match(rgb[r], best, cfg.overlay_colour_tolerance).mean() > 0.3]
    rows = np.array(rows, int)
    if len(rows) == 0:
        return rows, None, np.ones(W, bool)
    # Keep the contiguous block closest to zero_row
    blocks = np.split(rows, np.flatnonzero(np.diff(rows) > 1) + 1)
    rows = min(blocks, key=lambda b: abs(b.mean() - zero_row))
    presence = np.any(_colour_match(rgb[rows], best, cfg.overlay_colour_tolerance), axis=0)
    return rows, best, presence


def find_text(level: np.ndarray, overlay: np.ndarray, cfg: RenderConfig) -> np.ndarray:
    """White annotations (labels, scale ticks) drawn inside the spectral region.

    Both text and saturated flow reach the maximum grey level; text is a small
    bright blob on a dark background, saturated flow (and valve clicks) sit
    inside bright signal. Small bright components whose surroundings are dark
    are masked, dilated by one pixel to cover anti-aliasing.
    """
    bright = (level >= cfg.text_level) & ~overlay
    if not bright.any():
        return np.zeros_like(bright)
    lab, n = ndimage.label(bright, structure=np.ones((3, 3)))
    area = ndimage.sum(bright, lab, index=np.arange(1, n + 1))
    ring = ndimage.binary_dilation(bright, iterations=3) & ~bright & ~overlay
    # label the ring by the nearest component
    near = ndimage.grey_dilation(lab, size=(7, 7))
    with np.errstate(invalid="ignore", divide="ignore"):
        ring_mean = ndimage.mean(level, labels=np.where(ring, near, 0), index=np.arange(1, n + 1))
    ring_mean = np.nan_to_num(np.asarray(ring_mean, float), nan=0.0)
    is_text = (area <= cfg.text_max_area) & (ring_mean <= cfg.text_ring_max)
    mask = np.isin(lab, np.flatnonzero(is_text) + 1)
    return ndimage.binary_dilation(mask, iterations=1)


def find_clicks(level: np.ndarray, sweep: np.ndarray, dt: float, cfg: RenderConfig,
                return_strength: bool = False):
    """Columns holding a valve click (short broadband transient).

    With return_strength, also returns the transient height in robust SDs per
    column (used to rank clicks, e.g. for aortic valve closure)."""
    W = level.shape[1]
    E = level.mean(axis=0)
    E[sweep] = np.nan
    # White top-hat of the column-mean level: E minus its grey opening with a
    # flat window one maximum click-width wide. The opening removes only
    # features narrower than a click and keeps steps, so a flow onset/offset
    # gives ~0 while a click keeps its excess, also when it sits on the flank
    # of a jet (aortic closure at the end of ejection).
    m = max(1, int(round(cfg.click_max_width_s / dt)))
    x = np.arange(W)
    good = ~np.isnan(E)
    if good.sum() < 2 * m:
        z = np.zeros(W, bool)
        return (z, np.zeros(W)) if return_strength else z
    Ef = np.interp(x, x[good], E[good])  # bridge the sweep with the edge levels
    hp = Ef - ndimage.grey_opening(Ef, size=m + 2, mode="nearest")
    hp[sweep] = 0.0
    # the first/last columns of the data cannot be confirmed as transients
    edge = np.zeros(W, bool)
    for a, b in _runs(good):
        edge[a:min(a + m, b + 1)] = True
        edge[max(a, b - m + 1):b + 1] = True
    hp[edge] = 0.0
    sig = 1.4826 * np.median(np.abs(hp - np.median(hp))) + 1e-6
    cand = hp > cfg.click_min_snr * sig
    clicks = np.zeros(W, bool)
    for a, b in _runs(cand):
        if b - a + 1 <= m:
            clicks[max(0, a - 1):b + 2] = True
    if return_strength:
        # strength for every column (not only clicks): R-gated detectors such
        # as the aortic valve closure may use a lower threshold inside their window
        return clicks, hp / sig
    return clicks


def bridge_columns(level: np.ndarray, bad: np.ndarray) -> np.ndarray:
    """Replace columns `bad` by linear interpolation between the nearest good columns."""
    out = level.copy()
    good = np.flatnonzero(~bad)
    if len(good) < 2:
        return out
    for a, b in _runs(bad):
        left = a - 1 if a > 0 else None
        right = b + 1 if b < level.shape[1] - 1 else None
        if left is None or right is None or bad[left] or bad[right]:
            continue
        w = (np.arange(a, b + 1) - left) / (right - left)
        out[:, a:b + 1] = level[:, [left]] * (1 - w) + level[:, [right]] * w
    return out


def find_sweep(presence: np.ndarray, min_width: int) -> np.ndarray:
    """Columns without a drawn baseline, in runs at least min_width wide."""
    sweep = np.zeros_like(presence, bool)
    if presence.all():
        return sweep
    for s, e in _runs(~presence):
        if e - s + 1 >= min_width:
            sweep[s:e + 1] = True
    return sweep


def sweep_order(sweep: np.ndarray, align: bool) -> np.ndarray:
    """Column permutation that puts the oldest sample first.

    The display is a circular buffer: the band being written separates the
    newest samples (to its left) from the oldest (to its right). Rotating so
    that the record starts at the sweep makes time monotonic.
    """
    W = len(sweep)
    if not align or not sweep.any():
        return np.arange(W)
    runs = _runs(sweep)
    widths = [e - s + 1 for s, e in runs]
    # the buffer is circular: a sweep crossing the right edge continues at column 0
    if len(runs) > 1 and runs[0][0] == 0 and runs[-1][1] == W - 1:
        widths[-1] += widths[0]
        widths[0] = 0
    start = runs[int(np.argmax(widths))][0]
    return np.roll(np.arange(W), -start)


def fill_invalid_columns(level: np.ndarray, valid: np.ndarray) -> np.ndarray:
    """Fill invalid pixels by linear interpolation along each column.

    Thin overlays (baseline, markers, trace) are bridged from the pixels above
    and below. Columns without any valid pixel are left at 0.
    """
    out = level.astype(np.float32).copy()
    H = level.shape[0]
    rows = np.arange(H)
    bad_cols = np.flatnonzero((~valid).any(axis=0))
    for c in bad_cols:
        v = valid[:, c]
        if not v.any():
            out[:, c] = 0.0
            continue
        out[~v, c] = np.interp(rows[~v], rows[v], out[v, c])
    return out


def level_to_power(level: np.ndarray, dynamic_range_db: float) -> np.ndarray:
    """Undo log compression approximately: display level -> relative linear power.

    Assumes grey levels 0..255 span `dynamic_range_db` dB. The true mapping
    (dynamic range, reject, gain, post-processing curve) is not in the DICOM,
    so integrated-power methods on the image are an image-domain adaptation,
    not the signal-domain algorithms.
    """
    return np.power(10.0, (np.asarray(level, np.float64) / 255.0) * dynamic_range_db / 10.0) - 1.0


def classify_modality(region: Region, colormap: str, v_range: tuple[float, float]) -> str:
    if region.data_type == 4:
        return "CW"
    span = max(abs(v_range[0]), abs(v_range[1]))
    if colormap == "colour" or span < 40.0:
        return "TDI"
    return "PW"


def build_spectrogram(
    img: DicomImage,
    region: Region,
    cfg: RenderConfig,
    extra_overlay: np.ndarray | None = None,
) -> Spectrogram:
    """Crop, clean and calibrate the spectral Doppler region.

    extra_overlay: optional (H_img, W_img) mask of pixels known to be overlays
    (e.g. the ECG trace found by `ecg.extract_ecg`).
    """
    px = img.pixels
    rgb_full = px if px.ndim == 3 else np.repeat(px[..., None], 3, axis=2)
    rgb = rgb_full[region.y0:region.y1 + 1, region.x0:region.x1 + 1].copy()
    H, W, _ = rgb.shape

    # Zero-velocity row: the header is authoritative (the drawn line is several
    # pixels thick, and pixel detection can lock onto dense saturated flow).
    baseline_rows, base_colour, presence = find_baseline(
        rgb, region.ref_y0 if region.ref_y0 is not None else H / 2, cfg)
    if region.ref_y0 is not None:
        zero_row = float(region.ref_y0)
    elif len(baseline_rows):
        zero_row = float(baseline_rows.mean())
    else:
        raise ValueError("No ReferencePixelY0 and no drawn baseline: zero velocity unknown")
    info: dict[str, Any] = {}
    if len(baseline_rows) and not (baseline_rows.min() - 5 <= zero_row <= baseline_rows.max() + 5):
        info["warning_baseline_mismatch"] = (zero_row, baseline_rows.tolist())

    # --- overlays --------------------------------------------------------
    overlay = np.zeros((H, W), bool)
    if extra_overlay is not None:
        overlay |= extra_overlay[region.y0:region.y1 + 1, region.x0:region.x1 + 1]
    tol = cfg.overlay_colour_tolerance
    if base_colour is not None:
        chromatic_base = int(base_colour.max() - base_colour.min()) > cfg.chroma_threshold
        if chromatic_base:
            # Coloured baseline: the same colour is used for time markers.
            overlay |= _colour_match(rgb, base_colour, tol)
        else:
            overlay[baseline_rows] |= _colour_match(rgb[baseline_rows], base_colour, tol)
        overlay[baseline_rows] = True

    ch = rgb.astype(np.int16)
    chroma = ch.max(axis=2) - ch.min(axis=2)
    nonblack = ch.max(axis=2) > 8
    candidates = nonblack & ~overlay
    frac_colour = float((chroma[candidates] > cfg.chroma_threshold).mean()) if candidates.any() else 0.0
    colormap = "colour" if frac_colour > cfg.colormap_fraction else "grey"
    if colormap == "colour":
        # Grey pixels on a colour-map display are text, scale ticks or cursors.
        overlay |= nonblack & (chroma <= cfg.chroma_threshold // 2) & (ch.max(axis=2) > 60)
        level = (rgb.astype(np.float32) @ LUMA.astype(np.float32)) * COLORMAP_LEVEL_SCALE
    else:
        # Saturated colours on a grey display are overlays (ECG, markers, cursors).
        overlay |= chroma > cfg.chroma_threshold
        level = rgb.astype(np.float32).mean(axis=2)
        overlay |= find_text(level, overlay, cfg)
    level = np.clip(level, 0, 255)

    # --- sweep -------------------------------------------------------------
    sweep = find_sweep(presence, cfg.min_sweep_width_px) if len(baseline_rows) else np.zeros(W, bool)
    order = sweep_order(sweep, cfg.align_to_sweep)

    valid = ~overlay
    valid[:, sweep] = False
    level_filled = fill_invalid_columns(level, valid)
    level_filled[:, sweep] = 0.0

    velocity = (np.arange(H) - zero_row) * region.dy
    modality = classify_modality(region, colormap, (velocity.min(), velocity.max()))

    # Valve clicks: narrow, broadband, saturated vertical lines (the leaflets
    # themselves, not blood flow). Detected as transients of the column-mean
    # level (as the MATLAB AVC detector does). In 'bridge' mode (default) they
    # are interpolated over so that no envelope estimator follows them; their
    # times are reported separately (t_clicks, t_avc). Bridging applies only to
    # cfg.click_bridge_modalities: on TDI, narrow transients are mostly tissue
    # motion (isovolumic contraction/relaxation spikes), which the envelope
    # must keep, so TDI uses 'keep'.
    if cfg.click_mode not in ("bridge", "follow", "keep", "off"):
        raise ValueError(f"unknown click_mode '{cfg.click_mode}'")
    click_mode = cfg.click_mode
    if click_mode in ("bridge", "follow") and modality not in cfg.click_bridge_modalities:
        click_mode = "keep"
    if click_mode == "off":
        clicks, strength = np.zeros(W, bool), np.zeros(W)
    else:
        clicks, strength = find_clicks(level_filled, sweep, region.dx, cfg, return_strength=True)
    if clicks.any():
        info["click_columns"] = np.flatnonzero(clicks).tolist()
        if click_mode == "bridge":
            level_filled = bridge_columns(level_filled, clicks | sweep)
            level_filled[:, sweep] = 0.0
    info.update(colour_fraction=frac_colour, n_sweep_columns=int(sweep.sum()), display_zero_row=zero_row)

    return Spectrogram(
        level=level_filled, valid=valid, zero_row=zero_row, dy=float(region.dy), dt=float(region.dx),
        sweep=sweep, order=order, colormap=colormap, modality=modality, region=region,
        baseline_rows=baseline_rows, rgb=rgb, overlay=overlay, info=info,
        clicks=clicks, click_strength=strength, click_mode=click_mode,
    )


def dilate(mask: np.ndarray, r: int = 1) -> np.ndarray:
    return ndimage.binary_dilation(mask, iterations=r) if r > 0 else mask


# ==================================================================================================
# ecg.py: ECG extraction from the rendered trace, and R-peak detection.
# ==================================================================================================
# None of the example DICOMs stores the ECG as a WaveformSequence; it is only
# burned into the pixels, along the lower edge of the B-mode region, sharing
# the columns (and therefore the time axis) of the spectral display. It has no
# amplitude calibration, so amplitudes are arbitrary units.
#
# Differences from the MATLAB implementation (DICOM2waveform.m):
# - The trace colour is searched in a band of rows rather than on one row, so a
#   trace that does not cross the B-mode lower edge is still found.
# - Per column, the sample is the top or bottom of the drawn stroke at local
#   extremes (so R and S peaks keep their full amplitude) and the stroke centre
#   elsewhere, instead of always the top pixel.
# - Where several strokes share a column (greyscale images, where Doppler
#   pixels can have the trace's grey value), the one continuing the trace from
#   its neighbours is taken.

@dataclass
class ECGTrace:
    row: np.ndarray  # (W,) float row of the trace in full-image coordinates, NaN = none
    mask: np.ndarray  # (H_img, W_img) bool pixels of the drawn trace
    colour: np.ndarray | None
    found: bool
    clipped: bool = False


def _band_rows(img: DicomImage, spec: Region, bmode: Region | None, cfg: ECGConfig) -> tuple[int, int]:
    H = img.pixels.shape[0]
    top_ref = bmode.y1 if bmode is not None else spec.y0
    lo = max(0, top_ref - cfg.search_above_px)
    hi = min(H - 1, spec.y0 + cfg.search_margin_px)
    return lo, hi


def _find_trace_colour(band: np.ndarray, is_grey_image: bool, W: int, centre_row: int,
                       exclude: tuple = ()) -> np.ndarray | None:
    """Colour of the ECG trace in a band of rows (band: (h, W, 3)).

    The trace is the colour that spans most columns without being a
    horizontal line (the drawn baseline also spans every column).
    """
    ch = band.astype(np.int16)
    chroma = ch.max(axis=2) - ch.min(axis=2)
    if is_grey_image:
        # Grey image: the ECG is the most common non-black value on the rows
        # around the B-mode lower edge (as in the MATLAB implementation).
        lo, hi = max(0, centre_row - 3), min(band.shape[0], centre_row + 4)
        vals = band[lo:hi, :, 0].ravel()
        vals = vals[vals > 30]
        if len(vals) == 0:
            return None
        u, c = np.unique(vals, return_counts=True)
        cand = u[np.argsort(c)[::-1][:5]]
    else:
        px = band[chroma > 40]
        if len(px) == 0:
            return None
        u, c = np.unique(px, axis=0, return_counts=True)
        cand = u[np.argsort(c)[::-1][:8]]
    best, best_cov = None, 0.0
    for col in cand:
        colour = np.array([col, col, col]) if np.ndim(col) == 0 else np.asarray(col)
        if any(np.all(np.abs(colour.astype(int) - np.asarray(e, int)) <= 6) for e in exclude):
            continue
        m = _colour_match(band, colour, 4)
        cov = m.any(axis=0).mean()
        # A horizontal line (the drawn baseline) occupies only a few rows
        # overall; even a flat ECG has QRS deflections spanning many rows.
        rows = np.flatnonzero(m.sum(axis=1) > 0)
        line_like = len(rows) == 0 or (rows.max() - rows.min()) < 6
        if cov > best_cov and not line_like:
            best, best_cov = colour, cov
    if best is None or best_cov < 0.2:
        return None
    return best.astype(int)


def _column_samples(mask: np.ndarray, max_gap: int) -> np.ndarray:
    """One row per column from a (h, W) trace mask."""
    h, W = mask.shape
    runs_per_col = [_runs(mask[:, c]) for c in range(W)]
    centre = np.full(W, np.nan)
    for c, runs in enumerate(runs_per_col):
        if len(runs) == 1:
            centre[c] = 0.5 * (runs[0][0] + runs[0][1])
    # Resolve columns with several runs by continuity with the neighbours
    known = np.flatnonzero(~np.isnan(centre))
    for c, runs in enumerate(runs_per_col):
        if len(runs) > 1:
            if len(known):
                ref = np.interp(c, known, centre[known])
            else:
                ref = h / 2
            s, e = min(runs, key=lambda r: min(abs(r[0] - ref), abs(r[1] - ref)))
            centre[c] = 0.5 * (s + e)
            runs_per_col[c] = [(s, e)]
    y = centre.copy()
    for c in range(W):
        if not runs_per_col[c]:
            continue
        s, e = runs_per_col[c][0]
        left = centre[c - 1] if c > 0 else np.nan
        right = centre[c + 1] if c < W - 1 else np.nan
        nb = np.array([left, right])
        nb = nb[~np.isnan(nb)]
        if len(nb) == 0 or e - s < 2:
            continue
        if s < nb.min() - 1:  # stroke reaches above both neighbours: upward peak
            y[c] = s
        elif e > nb.max() + 1:  # reaches below both neighbours: downward peak
            y[c] = e
    # Interpolate short gaps
    valid = ~np.isnan(y)
    if valid.sum() >= 2:
        for s, e in _runs(~valid):
            if s == 0 or e == W - 1 or e - s + 1 > max_gap:
                continue
            y[s:e + 1] = np.interp(np.arange(s, e + 1), [s - 1, e + 1], [y[s - 1], y[e + 1]])
    return y


def extract_ecg(img: DicomImage, spec: Region, bmode: Region | None, cfg: ECGConfig,
                exclude_colours: tuple = ()) -> ECGTrace:
    """Locate the ECG trace over the columns of the spectral region."""
    px = img.pixels
    rgb = px if px.ndim == 3 else np.repeat(px[..., None], 3, axis=2)
    is_grey = px.ndim == 2 or bool(np.all(rgb[..., 0] == rgb[..., 1]) and np.all(rgb[..., 1] == rgb[..., 2]))
    lo, hi = _band_rows(img, spec, bmode, cfg)
    band = rgb[lo:hi + 1, spec.x0:spec.x1 + 1]
    W = band.shape[1]
    centre_row = (bmode.y1 - 1 - lo) if bmode is not None else (spec.y0 - lo)
    colour = _find_trace_colour(band, is_grey, W, centre_row, exclude_colours)
    full_mask = np.zeros(px.shape[:2], bool)
    if colour is None:
        return ECGTrace(row=np.full(W, np.nan), mask=full_mask, colour=None, found=False)

    m = _colour_match(band, colour, cfg.colour_tolerance)
    lab, n = ndimage.label(m, structure=np.ones((3, 3)))
    if n:
        objs = ndimage.find_objects(lab)
        widths = np.array([sl[1].stop - sl[1].start for sl in objs])
        keep = widths >= cfg.min_component_width_frac * W
        if not keep.any():
            keep = widths == widths.max()
        if not is_grey:
            # Colour image: the trace colour is unique, so also keep small
            # pieces within the vertical band of the main trace.
            rows_main = np.concatenate([np.arange(objs[i][0].start, objs[i][0].stop) for i in np.flatnonzero(keep)])
            r0, r1 = rows_main.min(), rows_main.max()
            for i, sl in enumerate(objs):
                if not keep[i] and sl[0].start >= r0 - 2 and sl[0].stop <= r1 + 3:
                    keep[i] = True
        m = np.isin(lab, np.flatnonzero(keep) + 1)
    max_gap = max(1, int(round(cfg.max_gap_s / spec.dx)))
    y = _column_samples(m, max_gap)
    full_mask[lo:hi + 1, spec.x0:spec.x1 + 1] = m
    found = bool(np.mean(~np.isnan(y)) > 0.2)
    # The scanner clips the drawn trace to its display box: flat runs at the
    # extreme row are clipped R (or S) waves.
    clipped = False
    if found:
        yr = y[~np.isnan(y)]
        clipped = bool(max(np.sum(yr <= yr.min() + 0.5), np.sum(yr >= yr.max() - 0.5)) > 0.02 * len(yr))
    return ECGTrace(row=y + lo, mask=full_mask, colour=colour, found=found, clipped=clipped)


def ecg_amplitude(row: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Trace rows -> (a.u. normalised, pixels upward). Isoelectric level ~ 0."""
    up = -(row - np.nanmedian(row)) if np.any(~np.isnan(row)) else row.copy()
    scale = np.nanmax(np.abs(up)) if np.any(~np.isnan(up)) else 1.0
    return up / (scale if scale > 0 else 1.0), up


# ---------------------------------------------------------------------------
# R-peak detection: port of DetectRpeaks.m (QRS-band energy, Pan-Tompkins style)
# ---------------------------------------------------------------------------

def _robust_std(x: np.ndarray) -> float:
    return 1.4826 * float(np.median(np.abs(x - np.median(x)))) + np.finfo(float).eps


def _find_peaks(E: np.ndarray, threshold: float, min_dist: int) -> tuple[np.ndarray, np.ndarray]:
    if len(E) == 0 or E.max() <= threshold:
        return np.array([]), np.array([], int)
    idx, props = signal.find_peaks(E, height=threshold, distance=max(1, min_dist))
    return props["peak_heights"], idx


def detect_rpeaks(ecg: np.ndarray, t: np.ndarray, cfg: ECGConfig, heart_rate_hint: float | None = None) -> np.ndarray:
    """R-peak times (s). NaN samples (e.g. the sweep) never produce a beat.

    heart_rate_hint (bpm, e.g. the DICOM HeartRate tag) sets the expected RR
    interval for search-back. A strip holds only 2-8 beats, so the median RR
    of the detected beats is a poor reference when a beat is missing.
    """
    valid = ~np.isnan(ecg)
    if valid.sum() < 3:
        return np.array([])
    i0, i1 = np.flatnonzero(valid)[[0, -1]]
    x = ecg[i0:i1 + 1].astype(float)
    ts = t[i0:i1 + 1]
    nodata = np.isnan(x)
    if nodata.any():
        k = np.arange(len(x))
        x[nodata] = np.interp(k[nodata], k[~nodata], x[~nodata])
    fs = 1.0 / np.mean(np.diff(ts))

    lo, hi = cfg.qrs_band_hz
    try:
        if hi >= fs / 2:
            raise ValueError
        sos = signal.butter(2, [lo, hi], btype="bandpass", fs=fs, output="sos")
        xb = signal.sosfiltfilt(sos, x)
    except ValueError:
        w = max(3, int(round(fs / lo)))
        xb = x - ndimage.uniform_filter1d(x, w, mode="nearest")
    E = (xb / _robust_std(xb)) ** 2
    E = ndimage.uniform_filter1d(E, max(1, int(round(cfg.energy_smooth_s * fs))), mode="nearest")
    E = E / (E.max() + np.finfo(float).eps)

    min_dist = int(round(cfg.refractory_s * fs))
    floor = max(np.median(E) * 2, 0.005)
    heights, locs = _find_peaks(E, floor, min_dist)
    if len(locs) == 0:
        return np.array([])
    qrs_level = np.median(heights[heights >= np.median(heights)])
    noise_floor = cfg.noise_floor_fraction * qrs_level
    thr = max(cfg.thresh_fraction * qrs_level, noise_floor)
    keep = heights >= thr
    heights, locs = heights[keep], locs[keep]

    # Search-back in abnormally long RR gaps
    if len(locs) >= 2 or (heart_rate_hint and len(locs) >= 1):
        rr_ref = np.median(np.diff(locs)) if len(locs) >= 2 else np.inf
        if heart_rate_hint and heart_rate_hint > 0:
            rr_ref = min(rr_ref, 60.0 / heart_rate_hint * fs)
        gap_thr = cfg.searchback_gap_ratio * rr_ref
        # Include the stretches before the first and after the last beat
        bounds = np.concatenate([[-min_dist], locs, [len(E) - 1 + min_dist]])
        add_l, add_h = [], []
        for a, b in zip(bounds[:-1], bounds[1:]):
            is_edge = a < 0 or b >= len(E)
            if (b - a > gap_thr) and not (is_edge and not heart_rate_hint):
                s, e = max(0, a + min_dist), min(len(E) - 1, b - min_dist)
                if e - s >= 3:
                    h, l = _find_peaks(E[s:e + 1], 0.5 * noise_floor, min_dist)
                    l = l + s
                    if len(l) == 0:
                        continue
                    # Pan-Tompkins search-back adds the single largest peak;
                    # prefer candidates at a plausible RR from a neighbour.
                    plaus = np.zeros(len(l), bool)
                    if np.isfinite(rr_ref):
                        for nb in (a, b):
                            if 0 <= nb < len(E):
                                plaus |= np.abs(np.abs(l - nb) - rr_ref) <= 0.3 * rr_ref
                    pool = np.flatnonzero(plaus) if plaus.any() else np.arange(len(l))
                    j = pool[int(np.argmax(h[pool]))]
                    add_l.append(int(l[j]))
                    add_h.append(float(h[j]))
        if add_l:
            locs = np.concatenate([locs, add_l]).astype(int)
            heights = np.concatenate([heights, add_h])
            o = np.argsort(locs)
            locs, heights = locs[o], heights[o]
            kept = np.zeros(len(locs), bool)
            last = -1
            for k in range(len(locs)):
                if last < 0 or locs[k] - locs[last] >= min_dist:
                    kept[k] = True
                    last = k
                elif heights[k] > heights[last]:
                    kept[last] = False
                    kept[k] = True
                    last = k
            locs, heights = locs[kept], heights[kept]

    # T-wave guard (RR-relative window)
    if len(locs) >= 2:
        med_h = np.median(heights)
        keep = np.ones(len(locs), bool)
        last = 0
        for k in range(1, len(locs)):
            rr = np.median(np.diff(locs[keep]))
            if not np.isfinite(rr):
                break
            d = locs[k] - locs[last]
            f0, f1 = cfg.twave_rr_fraction
            if (f0 * rr < d < f1 * rr and heights[k] < cfg.twave_relative_height * heights[last]
                    and heights[k] < cfg.twave_relative_height * med_h):
                keep[k] = False
            else:
                last = k
        locs = locs[keep]

    locs = locs[~nodata[locs]]
    # Refine to the local maximum of |ECG| deflection within +-40 ms
    w = max(1, int(round(0.04 * fs)))
    xc = x - np.median(x)
    refined = []
    for l in locs:
        s, e = max(0, l - w), min(len(x), l + w + 1)
        refined.append(s + int(np.argmax(np.abs(xc[s:e]))))
    return ts[np.array(refined, int)] if refined else np.array([])


# ==================================================================================================
# envelope/likelihood.py: Noise statistics and soft signal membership (Doppler-energy likelihood).
# ==================================================================================================
# The rendered display is nearly binary (noise ~ a few grey levels, signal
# ~200) and log-compressed, so gain acts approximately as an additive offset.
# Thresholds are therefore referenced to the measured noise floor rather than
# to fixed grey levels. Two estimates of where signal starts are combined,
# taking the lower:
#
# - a noise margin (median + max(margin, k * robust SD)), which sits just above
#   the noise and keeps the faint outer edge of the spectrum, but fails on very
#   dense spectra where the median and MAD no longer describe the noise;
# - Otsu's threshold, read from the histogram, which survives dense spectra but
#   is too high on clean displays.
#
# Membership ramps linearly from 0 just above the noise floor to 1 at that
# threshold, so faint flow counts partially instead of being cut (the key
# refinement of the MATLAB DP method).

@dataclass
class NoiseStats:
    level: float  # noise level (median of the image)
    spread: float  # robust SD of the noise
    otsu: float
    threshold: float  # membership reaches 1 here
    noise_top: float  # membership starts rising here


def otsu_threshold(values: np.ndarray, nbins: int = 256, value_range=(0.0, 255.0)) -> tuple[float, float]:
    """Otsu threshold and its effectiveness metric (between-class / total variance)."""
    values = np.asarray(values, float).ravel()
    values = values[np.isfinite(values)]
    if len(values) == 0:
        return float("nan"), 0.0
    hist, edges = np.histogram(values, bins=nbins, range=value_range)
    p = hist.astype(float) / max(hist.sum(), 1)
    centres = 0.5 * (edges[:-1] + edges[1:])
    w0 = np.cumsum(p)
    mu = np.cumsum(p * centres)
    mu_t = mu[-1]
    w1 = 1 - w0
    with np.errstate(divide="ignore", invalid="ignore"):
        sb = (mu_t * w0 - mu) ** 2 / (w0 * w1)
    sb[~np.isfinite(sb)] = 0
    i = int(np.argmax(sb))
    var_t = float(np.sum(p * (centres - mu_t) ** 2))
    em = float(sb[i] / var_t) if var_t > 0 else 0.0
    return float(edges[i + 1]), em


def noise_stats(spec, cfg: LikelihoodConfig) -> NoiseStats:
    vals = spec.level[spec.valid]
    if len(vals) == 0:
        return NoiseStats(0.0, 1.0, 128.0, 128.0, 0.0)
    level = float(np.median(vals))
    spread = float(1.4826 * np.median(np.abs(vals - level)))
    otsu, _ = otsu_threshold(vals)
    margin_thr = level + max(cfg.noise_margin, cfg.noise_spread_factor * spread)
    threshold = min(margin_thr, otsu)
    noise_top = level + cfg.soft_low_factor * max(spread, 1.0)
    return NoiseStats(level, spread, otsu, threshold, noise_top)


def membership(level: np.ndarray, ns: NoiseStats) -> np.ndarray:
    """Soft signal membership in [0, 1]."""
    return np.clip((level - ns.noise_top) / max(ns.threshold - ns.noise_top, 1.0), 0.0, 1.0)


def density_window(spec, cfg: LikelihoodConfig) -> tuple[int, int]:
    rows = cfg.density_window_px_rows
    if cfg.density_window_cm_s > 0:
        rows = max(1, int(round(cfg.density_window_cm_s / abs(spec.dy))))
    cols = cfg.density_window_px_cols
    if cfg.density_window_s > 0:
        cols = max(1, int(round(cfg.density_window_s / spec.dt)))
    return rows, cols


def local_density(m: np.ndarray, window: tuple[int, int]) -> np.ndarray:
    """Moving mean of membership over (rows, cols)."""
    return ndimage.uniform_filter(m.astype(float), size=window, mode="nearest")


def likelihood_image(spec, cfg: LikelihoodConfig, ns: NoiseStats | None = None) -> np.ndarray:
    """Local density of soft membership, i.e. P(pixel is inside the flow region)."""
    ns = ns or noise_stats(spec, cfg)
    m = membership(spec.level, ns)
    m[:, spec.sweep] = 0.0
    return local_density(m, density_window(spec, cfg))


# ==================================================================================================
# envelope/base.py: Common interface for envelope estimators.
# ==================================================================================================
# Every estimator returns, per column, the outer boundary of the spectrum on
# the positive side and on the negative side of the zero-velocity line, as a
# distance from the baseline in rows ("edge index" k: k = 0 is the zero
# velocity row, k increases with |v|). Sides are handled through `SideImage`,
# which flips the image so that every side looks the same (baseline at k = 0,
# increasing speed with k) whatever the display orientation (PhysicalDeltaY
# sign) and baseline position.
#
# A side without flow has its edge at k = 0 (velocity 0), so v_max and v_min
# are defined in every data column. Sweep columns are NaN.

SIDES = ("pos", "neg")


@dataclass
class SideImage:
    """One half of the spectrogram, re-indexed outward from the baseline."""

    level: np.ndarray  # (D, W) display level, overlays filled
    valid: np.ndarray  # (D, W)
    rows: np.ndarray  # (D,) original row index of each k
    speed_per_row: float  # |dy| (cm/s per row)
    sign: int  # +1 for the positive side, -1 for the negative side
    sweep: np.ndarray  # (W,) bool

    @property
    def depth(self) -> int:
        return self.level.shape[0]

    def velocity(self, k: np.ndarray | float) -> np.ndarray:
        return self.sign * np.asarray(k, float) * self.speed_per_row


def side_view(spec: Spectrogram, side: str, image: np.ndarray | None = None) -> SideImage:
    """Rows from the zero row outward on the given side.

    `image` (H, W) can replace spec.level (e.g. a preprocessed image).
    """
    img = spec.level if image is None else image
    H = img.shape[0]
    z = int(round(spec.zero_row))
    # Row index increases downward; velocity = (r - z) * dy.
    # Positive velocities lie at rows r with (r - z) * dy > 0.
    up_is_positive = spec.dy < 0
    if (side == "pos") == up_is_positive:
        rows = np.arange(z, -1, -1)
    else:
        rows = np.arange(z, H)
    rows = rows[(rows >= 0) & (rows < H)]
    return SideImage(
        level=img[rows], valid=spec.valid[rows], rows=rows,
        speed_per_row=abs(spec.dy), sign=1 if side == "pos" else -1, sweep=spec.sweep,
    )


@dataclass
class Context:
    """Shared, lazily computed per-image quantities."""

    spec: Spectrogram
    likelihood: LikelihoodConfig = field(default_factory=LikelihoodConfig)
    dp: DPConfig = field(default_factory=DPConfig)
    _noise: NoiseStats | None = None
    aliasing: dict[str, Any] = field(default_factory=dict)  # set by the pipeline

    @property
    def noise(self) -> NoiseStats:
        if self._noise is None:
            self._noise = noise_stats(self.spec, self.likelihood)
        return self._noise


@dataclass
class EnvelopeEstimate:
    """Outer edges in rows from the baseline (NaN in the sweep)."""

    k_pos: np.ndarray
    k_neg: np.ndarray
    conf_pos: np.ndarray | None = None
    conf_neg: np.ndarray | None = None
    method: str = ""
    params: dict[str, Any] = field(default_factory=dict)
    diagnostics: dict[str, Any] = field(default_factory=dict)

    def velocities(self, spec: Spectrogram) -> tuple[np.ndarray, np.ndarray]:
        """(v_max, v_min) in cm/s."""
        s = abs(spec.dy)
        return self.k_pos * s, -self.k_neg * s


class EnvelopeEstimator(ABC):
    """Base class. Subclasses set `name`, `klass` ('spectrum' | 'image') and
    `defaults`, and implement `estimate`.

    There is no fit(): nothing is learned. Parameters are passed at
    construction (from YAML via `make_estimator`) and recorded in the result.
    """

    name: ClassVar[str] = "base"
    klass: ClassVar[str] = "image"
    defaults: ClassVar[dict[str, Any]] = {}

    def __init__(self, **params: Any):
        unknown = set(params) - set(self.defaults)
        if unknown:
            raise KeyError(f"{self.name}: unknown parameter(s) {sorted(unknown)}")
        self.params = {**self.defaults, **params}

    @abstractmethod
    def estimate(self, ctx: Context) -> EnvelopeEstimate: ...

    def __call__(self, spec: Spectrogram, likelihood: LikelihoodConfig | None = None,
                 dp: DPConfig | None = None) -> EnvelopeEstimate:
        ctx = Context(spec, likelihood or LikelihoodConfig(), dp or DPConfig())
        return self.estimate(ctx)

    def _result(self, k_pos, k_neg, conf_pos=None, conf_neg=None, **diag) -> EnvelopeEstimate:
        return EnvelopeEstimate(k_pos=k_pos, k_neg=k_neg, conf_pos=conf_pos, conf_neg=conf_neg,
                                method=self.name, params=dict(self.params), diagnostics=diag)


class ColumnwiseEstimator(EnvelopeEstimator):
    """Estimators that treat every column (spectrum) independently.

    Subclasses implement `edge_column(spectrum, ctx) -> float` on a one-sided
    spectrum (index 0 = baseline) or override `edge_side` for vectorised code.
    """

    klass = "spectrum"

    def spectra(self, side: SideImage, ctx: Context) -> np.ndarray:
        """One-sided spectra (D, W) used by the method. Default: display level."""
        return side.level.astype(float)

    def edge_column(self, s: np.ndarray, ctx: Context) -> float:  # pragma: no cover
        raise NotImplementedError

    def edge_side(self, side: SideImage, ctx: Context) -> tuple[np.ndarray, np.ndarray | None]:
        S = self.spectra(side, ctx)
        W = S.shape[1]
        out = np.full(W, np.nan)
        for c in range(W):
            if side.sweep[c]:
                continue
            out[c] = self.edge_column(S[:, c], ctx)
        return out, None

    def estimate(self, ctx: Context) -> EnvelopeEstimate:
        res = {}
        for side in SIDES:
            sv = side_view(ctx.spec, side)
            k, conf = self.edge_side(sv, ctx)
            k = np.asarray(k, float)
            k[ctx.spec.sweep] = np.nan
            res[side] = (k, conf)
        return self._result(res["pos"][0], res["neg"][0], res["pos"][1], res["neg"][1])


# ==================================================================================================
# envelope/dp.py: Primary estimator: likelihood image + globally optimal boundary (dynamic programming).
# ==================================================================================================
# Port of `CalculateEnvelopeDP` from the MATLAB implementation, which was the
# best method against vendor ground truth (MAE 2.3 vs 18.1 cm/s for the legacy
# per-column method). For each side of the baseline the boundary path e(x)
# minimises
#
#     sum_x [ signal density beyond e(x)  +  non-signal between baseline and e(x) ]
#         + lambda * sum_x |e(x) - e(x-1)|
#
# i.e. the two-region split of every column, solved jointly over all columns.
# The L1 term is a physiological acceleration prior: one row per column is
# |dy|/dt cm/s^2, so lambda = (|dy|/dt) / a_ref makes it the same physical
# constraint on every image.
#
# Differences from the MATLAB version:
# - No two-state direction Viterbi: the requested outputs are the positive and
#   negative outer envelopes separately, both defined in every column (a side
#   without flow has its edge at the baseline, which the cost produces
#   naturally: with no signal density, e = 0 is cheapest).
# - The path is decoupled across the sweep (no transition penalty from the
#   columns before the sweep to those after it: they are not adjacent in time).
# - The distance transform uses a vectorised cumulative-minimum formulation.
# - Optional scaling of a_ref with the display velocity range (MATLAB open issue:
#   a fixed a_ref clipped systolic upstrokes on high-velocity-scale records).
#
# Plan.txt section 20 also proposed a second-order (curvature) term. That makes
# the state space quadratic in the number of rows (~400^2 states x ~900 columns)
# and was not adopted; curvature is controlled by optional post-smoothing.

def _l1_min_convolution(f: np.ndarray, lam: float, g: np.ndarray | None = None
                        ) -> tuple[np.ndarray, np.ndarray]:
    """h(i) = min_k f(k) + lam*|i-k| and the minimising k, in O(n).

    g: optional non-decreasing coordinate per state (g = lam*i by default); the
    distance is then |g(i) - g(k)|.
    """
    n = len(f)
    idx = np.arange(n)
    g = lam * idx if g is None else g
    # forward: min over k <= i of f(k) - g(k), plus g(i)
    a = f - g
    cm = np.minimum.accumulate(a)
    arg_f = np.maximum.accumulate(np.where(a <= cm, idx, 0))
    h_f = cm + g
    # backward: min over k >= i of f(k) + g(k), minus g(i)
    b = (f + g)[::-1]
    cmb = np.minimum.accumulate(b)
    ridx = idx[::-1]
    # position (in reversed array) of the running minimum
    pos = np.maximum.accumulate(np.where(b <= cmb, np.arange(n), 0))
    arg_b = ridx[pos][::-1]
    h_b = cmb[::-1] - g
    use_b = h_b < h_f
    return np.where(use_b, h_b, h_f), np.where(use_b, arg_b, arg_f)


def dp_solve(cost: np.ndarray, lam: float, free: np.ndarray | None = None,
             coords: np.ndarray | None = None) -> np.ndarray:
    """Minimise sum_x cost[e_x, x] + lam*|e_x - e_{x-1}| exactly.

    free: (W,) bool; the transition INTO column x is unpenalised where free[x]
    (used to decouple the path across the sweep).
    coords: optional (D, W), non-decreasing along axis 0; the transition into
    column x then costs |coords[e_x, x] - coords[e_{x-1}, x]| instead (lam unused).
    """
    D, W = cost.shape
    F = np.empty((D, W))
    P = np.empty((D, W), dtype=np.int32)
    F[:, 0] = cost[:, 0]
    P[:, 0] = np.arange(D)
    for x in range(1, W):
        if free is not None and free[x]:
            k = int(np.argmin(F[:, x - 1]))
            F[:, x] = cost[:, x] + F[k, x - 1]
            P[:, x] = k
        else:
            h, arg = _l1_min_convolution(F[:, x - 1], lam, None if coords is None else coords[:, x])
            F[:, x] = cost[:, x] + h
            P[:, x] = arg
    path = np.empty(W, dtype=np.int64)
    path[-1] = int(np.argmin(F[:, -1]))
    for x in range(W - 1, 0, -1):
        path[x - 1] = P[path[x], x]
    return path


def split_cost(density: np.ndarray, wall_rows: int = 0, wall_weight: float = 0.01) -> np.ndarray:
    """MATLAB cost ('split'): two-region split of each column.

        cost(k) = sum_{j > k} d_j + sum_{j <= k} w_j (1 - d_j)

    Assumes the flow region is filled from the baseline outward (true for CW,
    not for the PW spectral window or TDI bands). Rows j < wall_rows are nearly
    free to include (wall-filter band).
    """
    D = density.shape[0]
    w = np.ones((D, 1))
    w[:min(wall_rows, D)] = wall_weight
    beyond = density.sum(axis=0, keepdims=True) - np.cumsum(density, axis=0)
    return beyond + np.cumsum(w * (1.0 - density), axis=0)


def edge_cost(density: np.ndarray, theta: float = 0.2, inner_rows: int = 10,
              height_prior: float = 0.01, wall_rows: int = 0, wall_weight: float = 0.01) -> np.ndarray:
    """Outer-edge cost ('edge', default).

        cost(k) = sum_{j > k}           max(d_j - theta, 0)      signal left outside
                + sum_{j in (k-h, k]}   w_j max(theta - d_j, 0)  no signal just inside
                + height_prior * k                               weak prior toward no flow

    d = background-corrected local signal density, theta = density at which the
    edge is placed, h = inner_rows. The interior deeper than h is free, so hollow
    spectra (PW spectral window, TDI bands) are handled; pure noise (d < theta
    everywhere) gives k = 0 exactly; moving the edge outward through noise never
    lowers the cost. Rows in the wall band are nearly free to include.
    """
    D = density.shape[0]
    w = np.ones((D, 1))
    w[:min(wall_rows, D)] = wall_weight
    excess = np.clip(density - theta, 0.0, None)
    short = w * np.clip(theta - density, 0.0, None)
    beyond = excess.sum(axis=0, keepdims=True) - np.cumsum(excess, axis=0)
    sc = np.cumsum(short, axis=0)
    h = max(1, int(inner_rows))
    prev = np.zeros_like(sc)
    prev[h:] = sc[:-h]
    k = np.arange(D)[:, None]
    return beyond + (sc - prev) + height_prior * k


def column_margin(cost: np.ndarray, path: np.ndarray) -> np.ndarray:
    """Per-column confidence: how much better the chosen edge is than average."""
    best = cost[path, np.arange(cost.shape[1])]
    spread = cost.max(axis=0) - cost.min(axis=0)
    with np.errstate(invalid="ignore", divide="ignore"):
        m = (cost.mean(axis=0) - best) / spread
    m[~np.isfinite(m)] = 0.0
    return np.clip(m, 0.0, 1.0)


class DPEstimator(EnvelopeEstimator):
    """Soft noise-referenced membership -> local density -> DP boundary per side."""

    name = "dp"
    klass = "image"
    defaults = {
        "reference_accel_cm_s2": None,  # None -> DPConfig
        "accel_scale_with_range": None,  # None -> DPConfig
        "hard_threshold": False,  # ablation: binary membership instead of soft
        "use_density": True,  # ablation: raw membership instead of local density
    }

    def lambda_rows(self, ctx: Context) -> float:
        spec = ctx.spec
        a_ref = self.params["reference_accel_cm_s2"] or ctx.dp.reference_accel_cm_s2
        scale = self.params["accel_scale_with_range"]
        scale = ctx.dp.accel_scale_with_range if scale is None else scale
        if scale:
            lo, hi = spec.display_v_limits
            a_ref = a_ref * max(abs(lo), abs(hi)) / ctx.dp.reference_range_cm_s
        return (abs(spec.dy) / spec.dt) / a_ref

    def likelihood(self, ctx: Context) -> np.ndarray:
        spec = ctx.spec
        ns = ctx.noise
        if self.params["hard_threshold"]:
            m = (spec.level >= ns.threshold).astype(float)
        else:
            m = membership(spec.level, ns)
        m[:, spec.sweep] = 0.0
        if self.params["use_density"]:
            m = local_density(m, density_window(spec, ctx.likelihood))
        q = ctx.dp.background_percentile
        if q is not None and q > 0:
            # remove the density that pure noise produces, so that noise is
            # cost-neutral rather than an attraction toward the display limit
            valid = spec.valid & ~spec.sweep[None, :]
            bg = float(np.percentile(m[valid], q)) if valid.any() else 0.0
            if bg < 0.9:
                m = np.clip((m - bg) / (1.0 - bg), 0.0, 1.0)
        qn = ctx.dp.normalise_percentile
        if qn is not None and qn > 0:
            # express density relative to this image's in-flow density, so the
            # edge level theta means "fraction of typical flow density" whether
            # the flow renders dense (vascular PW/CW) or sparse (speckled TDI)
            valid = spec.valid & ~spec.sweep[None, :]
            top = float(np.percentile(m[valid], qn)) if valid.any() else 1.0
            m = np.clip(m / max(top, ctx.dp.normalise_floor), 0.0, 1.0)
        return m

    @staticmethod
    def local_normalise(d: np.ndarray, sweep: np.ndarray, dt: float, window_s: float, floor: float) -> np.ndarray:
        """Normalise a side's density by its local maximum over +-window_s (at least
        `floor`, relative to the globally normalised level 1)."""
        colmax = d.max(axis=0)
        colmax[sweep] = 0.0
        n = max(1, int(round(window_s / dt)))
        runmax = ndimage.maximum_filter1d(colmax, size=2 * n + 1, mode="nearest")
        return np.clip(d / np.maximum(runmax, floor)[None, :], 0.0, 1.0)

    def estimate(self, ctx: Context) -> EnvelopeEstimate:
        spec = ctx.spec
        L = self.likelihood(ctx)
        lam = self.lambda_rows(ctx)
        free = spec.sweep.copy()
        free[1:] |= spec.sweep[:-1]
        if spec.click_mode == "follow" and spec.clicks is not None and spec.clicks.any():
            # let the edge jump into and out of valve clicks
            free |= spec.clicks
            free[1:] |= spec.clicks[:-1]
        theta = ctx.dp.edge_density
        if spec.modality == "TDI" and ctx.dp.edge_density_tdi is not None:
            theta = ctx.dp.edge_density_tdi
        # relative sizes refer to the displayed span, also after unwrapping
        H = spec.display_height
        out = {}
        for side in SIDES:
            sv = side_view(spec, side, image=L)
            dens = sv.level
            if ctx.dp.local_norm_s > 0 and spec.modality in ctx.dp.local_norm_modalities:
                dens = self.local_normalise(dens, spec.sweep, spec.dt, ctx.dp.local_norm_s,
                                            ctx.dp.local_norm_floor)
            wall = int(round(ctx.dp.wall_band_rel * H))
            if ctx.dp.cost == "split":
                cost = split_cost(dens, wall_rows=wall)
            else:
                cost = edge_cost(dens, theta=theta,
                                 inner_rows=max(1, int(round(ctx.dp.inner_band_rel * H))),
                                 height_prior=ctx.dp.height_prior, wall_rows=wall)
            cost[:, spec.sweep] = 0.0
            path = dp_solve(cost, lam, free).astype(float)
            # an edge inside the wall band means no detectable flow on this side
            path[path <= wall] = 0.0
            conf = column_margin(cost, path.astype(int))
            path[spec.sweep] = np.nan
            conf[spec.sweep] = np.nan
            out[side] = (path, conf)
        return self._result(out["pos"][0], out["neg"][0], out["pos"][1], out["neg"][1],
                            likelihood=L, lambda_rows=lam)


# ==================================================================================================
# envelope/mean.py: Mean velocity envelopes, computed inside the detected flow region.
# ==================================================================================================
# For each column, pixels between the zero-velocity row and the outer edge on
# each side form the flow region. The mean velocity is the weighted average of
# their velocities:
#
#     v_mean_pos = sum_pos w v / sum_pos w      (positive half only)
#     v_mean_neg = sum_neg w v / sum_neg w      (negative half only)
#     v_mean     = sum_all w v / sum_all w      (both halves, signed)
#
# Restricting to the flow region stops the noise outside it from pulling the
# mean toward the centre of the display. Weights (MeanConfig.weighting):
#
# - 'power': de-compressed display level minus the de-compressed noise level,
#   an image-domain proxy of the power-weighted mean frequency (the physical
#   definition of mean velocity);
# - 'level': display level minus the noise level (log domain);
# - 'membership': soft signal membership.
#
# This is an image-domain estimate, not the scanner's Vmean. A side without flow
# (edge at the baseline) gets mean 0.

def pixel_weights(spec: Spectrogram, ns: NoiseStats, cfg: MeanConfig) -> np.ndarray:
    L = spec.level.astype(float)
    if cfg.weighting == "power":
        w = level_to_power(L, cfg.dynamic_range_db) - level_to_power(ns.level, cfg.dynamic_range_db)
    elif cfg.weighting == "level":
        w = L - ns.level
    elif cfg.weighting == "membership":
        w = membership(L, ns)
    else:
        raise ValueError(f"unknown weighting '{cfg.weighting}'")
    w = np.clip(w, 0.0, None)
    w[~spec.valid] = 0.0
    return w


def mean_envelopes(spec: Spectrogram, k_pos: np.ndarray, k_neg: np.ndarray,
                   ns: NoiseStats, cfg: MeanConfig) -> dict[str, np.ndarray]:
    """v_mean, v_mean_pos, v_mean_neg (cm/s) per column; NaN in the sweep."""
    w = pixel_weights(spec, ns, cfg)
    W = spec.level.shape[1]
    sums = {}
    k_clutter = cfg.clutter_band_cm_s / abs(spec.dy)
    for side, kk in (("pos", k_pos), ("neg", k_neg)):
        sv = side_view(spec, side, image=w)
        D = sv.depth
        k = np.arange(D)[:, None]
        edge = np.nan_to_num(kk, nan=-1.0)[None, :]
        inside = (k <= edge) & (k >= max(k_clutter, 0.0)) & (edge > 0)
        # the zero row itself carries no directional information
        inside &= k >= 1
        ww = np.where(inside, sv.level, 0.0)
        n = inside.sum(axis=0)
        sw = ww.sum(axis=0)
        swv = (ww * sv.velocity(np.arange(D))[:, None]).sum(axis=0)
        sums[side] = (sw, swv, n)
    out = {}
    for side in ("pos", "neg"):
        sw, swv, n = sums[side]
        with np.errstate(invalid="ignore", divide="ignore"):
            m = np.where((sw > 0) & (n >= cfg.min_pixels), swv / sw, 0.0)
        out[f"v_mean_{side}"] = m
    sw = sums["pos"][0] + sums["neg"][0]
    swv = sums["pos"][1] + sums["neg"][1]
    with np.errstate(invalid="ignore", divide="ignore"):
        out["v_mean"] = np.where(sw > 0, swv / sw, 0.0)
    for key in out:
        out[key] = out[key].astype(float)
        out[key][spec.sweep] = np.nan
    return out


# ==================================================================================================
# envelope/postprocess.py: Envelope post-processing (Plan section 21): median, Savitzky-Golay, Kalman.
# ==================================================================================================
# Applied to a velocity series in time order. NaN runs (the sweep) split the
# series into independent segments; nothing is smoothed across them.

def _segments(valid: np.ndarray) -> list[tuple[int, int]]:
    m = np.concatenate([[False], valid, [False]]).astype(np.int8)
    d = np.diff(m)
    return list(zip(np.flatnonzero(d == 1), np.flatnonzero(d == -1)))


def kalman_smooth(z: np.ndarray, dt: float, q: float, r: float, order: int = 2, rts: bool = True) -> np.ndarray:
    """Constant-velocity (order=2) or constant-acceleration (order=3) Kalman
    filter with Rauch-Tung-Striebel smoothing.

    q: SD of the white acceleration (order 2) or jerk (order 3) driving noise.
    r: measurement noise SD (same units as z).
    """
    n = len(z)
    if n == 0:
        return z
    if order == 2:
        F = np.array([[1, dt], [0, 1]])
        G = np.array([[dt ** 2 / 2], [dt]])
    else:
        F = np.array([[1, dt, dt ** 2 / 2], [0, 1, dt], [0, 0, 1]])
        G = np.array([[dt ** 3 / 6], [dt ** 2 / 2], [dt]])
    Q = G @ G.T * q ** 2
    Hm = np.zeros((1, order))
    Hm[0, 0] = 1.0
    x = np.zeros(order)
    x[0] = z[0]
    P = np.eye(order) * (r ** 2 * 10)
    xs_f, Ps_f, xs_p, Ps_p = [], [], [], []
    for k in range(n):
        if k:
            x = F @ x
            P = F @ P @ F.T + Q
        xs_p.append(x.copy())
        Ps_p.append(P.copy())
        S = Hm @ P @ Hm.T + r ** 2
        K = P @ Hm.T / S
        x = x + (K * (z[k] - Hm @ x)).ravel()
        P = (np.eye(order) - K @ Hm) @ P
        xs_f.append(x.copy())
        Ps_f.append(P.copy())
    if not rts:
        return np.array([xf[0] for xf in xs_f])
    xs = xs_f[-1].copy()
    out = np.empty(n)
    out[-1] = xs[0]
    for k in range(n - 2, -1, -1):
        C = Ps_f[k] @ F.T @ np.linalg.inv(Ps_p[k + 1])
        xs = xs_f[k] + C @ (xs - xs_p[k + 1])
        out[k] = xs[0]
    return out


def smooth_series(v: np.ndarray, dt: float, cfg: PostConfig, pixel_cm_s: float = 1.0) -> np.ndarray:
    """Smooth a velocity series (time order), segment by segment."""
    if cfg.method == "none":
        return v
    out = v.copy()
    for a, b in _segments(~np.isnan(v)):
        seg = v[a:b]
        if cfg.method == "median":
            n = max(1, int(round(cfg.median_window_s / dt))) | 1
            out[a:b] = ndimage.median_filter(seg, size=n, mode="nearest")
        elif cfg.method == "savgol":
            n = max(cfg.savgol_order + 2, int(round(cfg.savgol_window_s / dt)) | 1)
            if len(seg) > n:
                out[a:b] = signal.savgol_filter(seg, n, cfg.savgol_order, mode="interp")
        elif cfg.method in ("kalman_cv", "kalman_ca"):
            r = cfg.kalman_r_cm_s or 2.0 * pixel_cm_s
            order = 2 if cfg.method == "kalman_cv" else 3
            out[a:b] = kalman_smooth(seg, dt, cfg.kalman_q, r, order)
        else:
            raise ValueError(f"unknown post-processing '{cfg.method}'")
    return out


# ==================================================================================================
# quality.py: Quality indicators: image-domain SNR proxy, aliasing and coverage flags.
# ==================================================================================================
# The SNR here is an *image-domain SNR proxy*: the ratio of mean de-compressed
# display power inside the detected flow region to that outside it. It is not
# an acquisition SNR.

def flow_mask(spec: Spectrogram, k_pos: np.ndarray, k_neg: np.ndarray) -> np.ndarray:
    """(H, W) mask of the flow region between the two outer edges."""
    H, W = spec.level.shape
    M = np.zeros((H, W), bool)
    for side, kk in (("pos", k_pos), ("neg", k_neg)):
        sv = side_view(spec, side)
        edge = np.nan_to_num(kk, nan=-1.0)
        inside = (np.arange(sv.depth)[:, None] <= edge[None, :]) & (edge[None, :] > 0)
        M[sv.rows] |= inside
    M[:, spec.sweep] = False
    return M


def snr_proxy_db(spec: Spectrogram, flow: np.ndarray, dynamic_range_db: float = 40.0) -> float:
    valid = spec.valid & ~spec.sweep[None, :]
    P = level_to_power(spec.level, dynamic_range_db)
    sig = P[flow & valid]
    bg = P[~flow & valid]
    if len(sig) < 10 or len(bg) < 10:
        return float("nan")
    return float(10 * np.log10(max(sig.mean(), 1e-12) / max(bg.mean(), 1e-12)))


def aliasing_suspected(spec: Spectrogram, k_pos: np.ndarray, k_neg: np.ndarray, cfg: AliasingConfig) -> bool:
    """PW aliasing wraps flow around the display: where it happens, flow leaves
    one velocity limit and re-enters at the opposite one, so in the same
    columns both outer edges reach their display limits. (One edge alone at
    its limit is common: e.g. a mirror/clutter texture filling a small side.)
    """
    if spec.modality == "CW":
        return False
    data = ~spec.sweep
    if not data.any():
        return False
    touch = []
    for side, kk in (("pos", k_pos), ("neg", k_neg)):
        D = side_view(spec, side).depth
        touch.append(np.nan_to_num(kk, nan=0) >= (1 - cfg.alias_edge_fraction) * (D - 1))
    both = touch[0] & touch[1]
    return bool(both[data].mean() > cfg.alias_min_fraction)


# ==================================================================================================
# aliasing.py: Aliasing correction for PW / TDI displays (automatic per-column baseline shift).
# ==================================================================================================
# A pulsed-wave spectrum is periodic in velocity with the period of the display
# span (the Nyquist range): flow faster than one display limit re-enters at the
# other. The scanner's display window is therefore arbitrary, and a sonographer
# fixes aliasing by shifting the baseline. This module does the same, per
# column:
#
# 1. The display is treated as circular (row r == row r + H).
# 2. A *cut path* is found through the circular display, away from the
#    zero-velocity zone, that crosses the least signal, with a smoothness prior
#    (dynamic programming over the cut position). Without evidence the cut
#    stays at the display edge (no change). Between columns the cut may not
#    jump through signal present in both: a flow band stays on one side of the
#    cut, so the cut follows a wrapped band as it grows instead of tearing
#    through it to the other side.
# 3. Rows beyond the cut are moved by one period (+-H rows): rows beyond a cut
#    in the top part become velocities past the bottom limit and vice versa.
#    The result is a taller, unwrapped Spectrogram on which every estimator,
#    the mean envelopes and the flow mask run unchanged.
#
# The correction is only attempted when the wrap-around test fires
# (`quality.aliasing_suspected`) and only applied when the cut path carries
# clearly less signal than the display edge. It cannot resolve flows whose
# combined spread exceeds the Nyquist range in the same column; those remain
# (and stay flagged).

@dataclass
class UnwrapResult:
    spec: Spectrogram
    applied: bool
    cut_rows: np.ndarray  # (W,) cut row per column in display coordinates (-1 = none)
    edge_cost: float
    path_cost: float
    n_columns: int  # columns in which rows were moved
    shift_up: int  # rows added above the display
    shift_down: int  # rows added below the display


def _arc_rows(H: int, z: int, guard: int) -> tuple[np.ndarray, int]:
    """Allowed cut rows as one linear coordinate running from the zero-row side of
    the bottom part, through the display edge (row H-1 -> row 0), to the zero-row
    side of the top part. Returns (rows, index of the display edge)."""
    bottom = np.arange(min(H - 1, z + guard), H)  # rows below the zero row
    top = np.arange(0, max(0, z - guard) + 1)  # rows above the zero row
    rows = np.concatenate([bottom, top])
    return rows, len(bottom) - 1  # index of row H-1; the next index is row 0


def find_cut(density: np.ndarray, zero_row: float, sweep: np.ndarray, cfg: AliasingConfig
             ) -> tuple[np.ndarray, float, float]:
    """Cut row per column (display coordinates) and the costs of the cut path and of
    the display edge (mean signal density crossed per column)."""
    H, W = density.shape
    z = int(round(zero_row))
    guard = max(1, int(round(cfg.guard_rel * H)))
    rows, i_edge = _arc_rows(H, z, guard)
    d = ndimage.uniform_filter1d(density, max(1, cfg.cut_smooth_rows), axis=0, mode="wrap")
    cost = d[rows].copy()
    u = np.arange(len(rows))
    # without evidence stay at the display edge (between rows H-1 and 0)
    cost += cfg.edge_preference * np.minimum(np.abs(u - i_edge), np.abs(u - (i_edge + 1)))[:, None]
    cost[:, sweep] = 0.0
    free = sweep.copy()
    free[1:] |= sweep[:-1]
    # transition x-1 -> x: cut_lambda per row + cut_cross_weight per unit of density
    # passed over (present in both columns, so following a growing band is free)
    da = np.clip(d[rows], 0.0, None)
    both = np.minimum(da, np.roll(da, 1, axis=1))
    coords = cfg.cut_lambda * u[:, None] + cfg.cut_cross_weight * np.cumsum(both, axis=0)
    path = dp_solve(cost, cfg.cut_lambda, free, coords)
    cut = rows[path]
    data = ~sweep
    path_cost = float(d[cut, np.arange(W)][data].mean()) if data.any() else 0.0
    edge_cost = float(0.5 * (d[0] + d[H - 1])[data].mean()) if data.any() else 0.0
    return cut, path_cost, edge_cost


def unwrap(spec: Spectrogram, density: np.ndarray, cfg: AliasingConfig) -> UnwrapResult:
    """Unwrap the spectrogram along the least-signal cut path (see module docstring)."""
    H, W = spec.level.shape
    z = spec.zero_row
    cut, path_cost, edge_cost = find_cut(density, z, spec.sweep, cfg)
    zi = int(round(z))
    # rows to move per column: below-zero part -> cut c > z: rows c+1..H-1 move up (r - H)
    #                          above-zero part -> cut c < z: rows 0..c-1 move down (r + H)
    n_up = np.where(cut > zi, H - 1 - cut, 0)
    n_down = np.where(cut < zi, cut, 0)
    n_up[spec.sweep] = 0
    n_down[spec.sweep] = 0
    moved = (n_up > 0) | (n_down > 0)
    improves = path_cost < cfg.max_cost_ratio * edge_cost and edge_cost > cfg.min_edge_density
    if not moved.any() or not improves:
        return UnwrapResult(spec, False, np.full(W, -1), edge_cost, path_cost, 0, 0, 0)

    T = int(n_up.max())
    B = int(n_down.max())
    Hn = H + T + B
    bg = float(np.median(spec.level[spec.valid])) if spec.valid.any() else 0.0

    def remap(arr: np.ndarray, fill) -> np.ndarray:
        out = np.full((Hn,) + arr.shape[1:], fill, dtype=arr.dtype)
        out[T:T + H] = arr
        for x in np.flatnonzero(n_up > 0):
            k = n_up[x]
            out[T - k:T, x] = arr[H - k:H, x]  # row r -> r - H
            out[T + H - k:T + H, x] = fill
        for x in np.flatnonzero(n_down > 0):
            k = n_down[x]
            out[T + H:T + H + k, x] = arr[0:k, x]  # row r -> r + H
            out[T:T + k, x] = fill
        return out

    new = copy.copy(spec)
    new.level = remap(spec.level.astype(np.float32), np.float32(bg))
    new.valid = remap(spec.valid, True)
    new.valid[:, spec.sweep] = False
    if spec.overlay is not None:
        new.overlay = remap(spec.overlay, False)
    if spec.rgb is not None:
        new.rgb = remap(spec.rgb, np.uint8(0))
    new.zero_row = z + T
    new.baseline_rows = spec.baseline_rows + T
    new.info = dict(spec.info)
    new.info["aliasing_unwrapped"] = {"columns": int(moved.sum()), "rows_up": T, "rows_down": B}
    return UnwrapResult(new, True, np.where(moved, cut, -1), edge_cost, path_cost, int(moved.sum()), T, B)


