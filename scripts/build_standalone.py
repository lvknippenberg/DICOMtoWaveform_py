"""Build the single-file standalone script and its documented YAML from the package.

    python scripts/build_standalone.py          # (re)write standalone/
    python scripts/build_standalone.py --check  # exit 1 if standalone/ is out of date

The package (dicom2waveform/) is the only source. This script concatenates the modules of the
production path (DP envelope, ECG, aliasing, plots, command line) into
standalone/dicom2waveform_standalone.py, and writes the configuration with its comments
(dicom2waveform/config.py) to standalone/dicom2waveform_config.yaml. Never edit those two files by
hand; tests/test_standalone.py fails when they are out of date.

How the modules are joined: each module's docstring becomes a section banner, its top-level
imports are merged into one import block (relative imports are dropped, since all names now live
in one namespace), and the rest is copied verbatim. A name defined at top level in two modules is
an error. A relative import inside a function is allowed only inside a try block whose handler
catches ImportError (that is how the package reaches code that the standalone script leaves out,
such as the benchmark estimators).
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "dicom2waveform"
OUT_PY = ROOT / "standalone" / "dicom2waveform_standalone.py"
OUT_YAML = ROOT / "standalone" / "dicom2waveform_config.yaml"

# production path, in dependency order
MODULES = ["config", "io", "render", "ecg", "envelope/likelihood", "envelope/base", "envelope/dp",
           "envelope/mean", "envelope/postprocess", "quality", "aliasing", "pipeline", "plot", "cli"]

HEADER = '''"""dicom2waveform_standalone: ECG and Doppler envelopes from spectral / tissue Doppler DICOMs.

GENERATED by scripts/build_standalone.py from the dicom2waveform package (version {version}).
Do not edit this file: change the package and rebuild, so the two stay identical.

Single-file version of the package's production path: noise-referenced soft membership +
dynamic-programming envelope, aliasing correction, ECG and R-peaks, valve clicks and aortic valve
closure. The benchmark estimators, synthetic data and evaluation code are left out. The method is
explained step by step in docs/explainer/explainer.pdf of the repository.

Given a single-frame spectral Doppler (PW, CW) or tissue Doppler (TDI) DICOM, i.e. the rendered
display as stored by the scanner, it returns on one shared time axis:

    t           s, oldest sample first (the display's circular sweep is undone)
    ecg         a.u., traced from the burned-in ECG; isoelectric ~0, max |deflection| = 1
    v_max       cm/s, outer edge of the positive spectrum (>= 0; 0 when no flow on that side)
    v_min       cm/s, outer edge of the negative spectrum (<= 0; 0 when no flow)
    v_mean      cm/s, intensity-weighted mean velocity inside the detected flow region (signed)
    v_mean_pos  cm/s, same, positive half only
    v_mean_neg  cm/s, same, negative half only

plus event times t_rpeaks (R-peaks), t_clicks (valve clicks), t_avc (aortic valve closure)
and quality flags (modality, aliasing, ECG clipping, SNR proxy, ...).

Velocities carry the sign of the DICOM header (PhysicalDeltaY): on a display the operator
inverted, this is opposite to the on-screen label. NaN marks samples without data (the
sweep band of the display).

Usage as a module
-----------------
    from dicom2waveform_standalone import extract_waveforms, plot_result
    res = extract_waveforms("file.dcm")                         # built-in defaults
    res = extract_waveforms("file.dcm", "my_config.yaml")       # overrides from YAML
    res = extract_waveforms("file.dcm", {{"dp": {{"edge_density": 0.4}}}})
    res.t, res.ecg, res.v_max, res.v_min, res.v_mean, res.t_rpeaks, res.flags
    res.to_csv("out.csv")
    res = extract_waveforms("file.dcm", {{"keep_diagnostics": True}}); plot_result(res, "out.png")

Usage from the command line
---------------------------
    python dicom2waveform_standalone.py file.dcm [more.dcm ...] [--config cfg.yaml]
                                        [--out-dir DIR] [--plot]
    python dicom2waveform_standalone.py --write-config my_config.yaml

Every tunable parameter is documented, with its default, in the configuration classes below
(section config.py) and in dicom2waveform_config.yaml, which is generated from them. The YAML file
is optional; give only the keys you want to change.

Requirements: numpy, scipy, pydicom. Optional: pyyaml (YAML config), matplotlib
(plot_result, plot_overlay), pylibjpeg / pylibjpeg-libjpeg (JPEG-compressed DICOMs).

Note: DICOMs and full-frame renderings contain burned-in patient identifiers. The QC
figure shows only the spectral region and ECG strip, but treat it as patient data anyway.
"""
'''

FOOTER = '''

if __name__ == "__main__":
    raise SystemExit(main())
'''

RULE = "# " + "=" * 98


def _package_version() -> str:
    m = re.search(r'^__version__\s*=\s*"([^"]+)"', (PKG / "__init__.py").read_text(encoding="utf8"), re.M)
    if not m:
        raise SystemExit("no __version__ in dicom2waveform/__init__.py")
    return m.group(1)


def _top_level_names(node: ast.stmt) -> list[str]:
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return [node.name]
    if isinstance(node, ast.Assign):
        return [t.id for t in node.targets if isinstance(t, ast.Name)]
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return [node.target.id]
    return []


def _check_nested_relative_imports(tree: ast.Module, name: str) -> None:
    guarded = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Try) and any(
                h.type is not None and "ImportError" in ast.unparse(h.type) for h in node.handlers):
            for st in node.body:
                guarded.update(id(n) for n in ast.walk(st))
    for top in tree.body:
        if isinstance(top, (ast.Import, ast.ImportFrom)):
            continue
        for node in ast.walk(top):
            if isinstance(node, ast.ImportFrom) and node.level > 0 and id(node) not in guarded:
                raise SystemExit(f"{name}.py:{node.lineno}: relative import inside a function must sit in a "
                                 f"try block that catches ImportError (it fails in the standalone script)")


def _split_module(name: str, imports: dict, from_imports: dict, defined: dict) -> str:
    path = PKG / f"{name}.py"
    src = path.read_text(encoding="utf8")
    lines = src.splitlines()
    tree = ast.parse(src)
    _check_nested_relative_imports(tree, name)
    drop: set[int] = set()
    doc = ""
    for i, node in enumerate(tree.body):
        span = range(node.lineno - 1, node.end_lineno)
        if i == 0 and isinstance(node, ast.Expr) and isinstance(getattr(node, "value", None), ast.Constant) \
                and isinstance(node.value.value, str):
            doc = node.value.value.strip()
            drop.update(span)
        elif isinstance(node, ast.Import):
            drop.update(span)
            for a in node.names:
                imports.setdefault((a.name, a.asname), None)
        elif isinstance(node, ast.ImportFrom):
            drop.update(span)
            if node.level == 0 and node.module != "__future__":
                bucket = from_imports.setdefault(node.module, {})
                for a in node.names:
                    bucket.setdefault((a.name, a.asname), None)
        elif _top_level_names(node) == ["__all__"]:
            drop.update(span)
        else:
            for n in _top_level_names(node):
                if n in defined:
                    raise SystemExit(f"'{n}' is defined at top level in both {defined[n]}.py and {name}.py")
                defined[n] = name
    body = [line for i, line in enumerate(lines) if i not in drop]
    text = re.sub(r"\n{4,}", "\n\n\n", "\n".join(body)).strip("\n")
    doc_lines = doc.splitlines() or [""]
    banner = [RULE, f"# {name}.py: {doc_lines[0]}".rstrip(), RULE]
    rest = [f"# {line}".rstrip() for line in doc_lines[1:]]
    while rest and rest[0] == "#":
        rest.pop(0)
    return "\n".join(banner + rest) + "\n\n" + text + "\n"


def _import_block(imports: dict, from_imports: dict) -> str:
    def group(mod: str) -> int:
        return 0 if mod.split(".")[0] in sys.stdlib_module_names else 1

    lines = {0: [], 1: []}
    for name, asname in imports:
        lines[group(name)].append(f"import {name}" + (f" as {asname}" if asname else ""))
    for mod, names in from_imports.items():
        items = ", ".join(n + (f" as {a}" if a else "") for n, a in sorted(names))
        lines[group(mod)].append(f"from {mod} import {items}")
    return "\n\n".join("\n".join(sorted(v, key=lambda s: (s.startswith("from"), s))) for v in lines.values() if v)


def build() -> tuple[str, str]:
    """(standalone script, YAML) as text."""
    version = _package_version()
    imports: dict = {}
    from_imports: dict = {}
    defined: dict = {}
    sections = [_split_module(m, imports, from_imports, defined) for m in MODULES]
    py = (HEADER.format(version=version) + "\nfrom __future__ import annotations\n\n"
          + _import_block(imports, from_imports)
          + f'\n\n__version__ = "{version}-standalone"\n\n\n' + "\n\n".join(sections).rstrip("\n") + "\n" + FOOTER)
    ast.parse(py)  # must be valid Python

    sys.path.insert(0, str(ROOT))
    from dicom2waveform.config import config_yaml

    return py, config_yaml()


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="only check that standalone/ is up to date")
    a = p.parse_args()
    py, yml = build()
    stale = [path for path, text in ((OUT_PY, py), (OUT_YAML, yml))
             if not path.exists() or path.read_text(encoding="utf8") != text]
    if a.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run python scripts/build_standalone.py)")
        return 1 if stale else 0
    for path, text in ((OUT_PY, py), (OUT_YAML, yml)):
        path.write_text(text, encoding="utf8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
