"""Regenerate configs/default.yaml from the dataclass defaults in dicom2waveform/config.py.

Usage: python scripts/write_default_config.py
tests/test_config.py fails when the file is out of date.
"""
from pathlib import Path

from dicom2waveform.config import PipelineConfig, write_config

PATH = Path(__file__).resolve().parents[1] / "configs" / "default.yaml"

if __name__ == "__main__":
    write_config(PipelineConfig(), PATH,
                 header="Default configuration, generated by scripts/write_default_config.py from\n"
                        "dicom2waveform/config.py (documentation lives there). Do not edit by hand.")
    print(f"wrote {PATH}")
