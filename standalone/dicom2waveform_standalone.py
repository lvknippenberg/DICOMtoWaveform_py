    ax.imshow(px, extent=(-0.5, Wimg - 0.5, H - 0.5, -0.5), interpolation="nearest")
    if panel is not None:
        hp = panel.shape[0]
        axp = fig.add_axes([0, 0, 1, hp / Htot])
